"""mergekit integration: YAML emitter + out-of-process merge driver.

mergekit 0.1.x pins ``huggingface_hub>=1.31`` while transformers 4.x pins
``huggingface_hub<1.0``.  Installing mergekit inside a transformers-4.x
environment therefore breaks that environment.  ZeroAI keeps mergekit *outside*
the main interpreter: the YAML is always produced (and is unit-testable without
mergekit installed), and the actual merge is executed by a driver script run
with ``python_executable``, which can point at a dedicated mergekit venv.
"""

from __future__ import annotations

import json
import logging
import os
import subprocess
import sys
from typing import Dict, List, Optional, Sequence

import yaml

from zeroai.merge.backend import MergeBackend
from zeroai.schemas import MergePlan, MergedArtifact

LOG = logging.getLogger(__name__)


def _block_weights(plan: MergePlan, model_index: int) -> List[float]:
    row = plan.weights[model_index]
    rounded = [round(float(value), 6) for value in row]
    if len(set(rounded)) == 1:
        return rounded  # keep the explicit list: it documents the block layout
    return rounded


def build_mergekit_yaml(plan: MergePlan) -> str:
    """Render a :class:`MergePlan` as a mergekit configuration document.

    The layout matches section 3.1 of the technical specification.  Per-block
    coefficients are emitted as mergekit *interpolated gradients* (a list of
    scalars that mergekit linearly interpolates over the normalized layer
    position ``t``), which is mergekit's native mechanism for layer-wise weights.
    """
    plan.validate()

    models: List[Dict[str, object]] = []
    for index, model in enumerate(plan.models):
        parameters: Dict[str, object] = {"weight": _block_weights(plan, index)}
        if plan.method.uses_trim:
            parameters["density"] = round(plan.density, 6)
        if plan.method.uses_dare:
            # mergekit's ``density`` is the retained fraction for every
            # sparsification strategy, so the drop gene has to be inverted.
            parameters["density"] = round(1.0 - plan.dare_density, 6)
            parameters["rescale_norm"] = "l2"
        if plan.normalize:
            parameters["normalize"] = True
        models.append({"model": model.path, "parameters": parameters})

    document: Dict[str, object] = {
        "models": models,
        "merge_method": plan.method.mergekit_method,
        "base_model": plan.base_model.path,
        "parameters": {
            "density": round(plan.density, 6),
            "normalize": bool(plan.normalize),
        },
        "dtype": plan.dtype.value,
    }

    header = (
        "# Generated by ZeroAI CandidateGenerator\n"
        f"# method={plan.method.value} blocks={plan.n_blocks} "
        f"density(keep)={plan.density:.4f} dare_drop={plan.dare_density:.4f} "
        f"dare_scale={plan.dare_scale:.4f}\n"
    )
    body = yaml.safe_dump(document, sort_keys=False, default_flow_style=False)
    return header + body


class MergekitBackend(MergeBackend):
    """Run the merge through mergekit in a separate Python interpreter."""

    name = "mergekit"

    def __init__(
        self,
        python_executable: Optional[str] = None,
        device: str = "cpu",
        low_cpu_memory: bool = False,
        trust_remote_code: bool = False,
        write_model_card: bool = False,
        quiet: bool = True,
        timeout_seconds: int = 7200,
    ):
        self.python_executable = python_executable or sys.executable
        self.device = device
        self.low_cpu_memory = low_cpu_memory
        self.trust_remote_code = trust_remote_code
        self.write_model_card = write_model_card
        self.quiet = quiet
        self.timeout_seconds = timeout_seconds

    # ------------------------------------------------------------- capability
    @staticmethod
    def is_available(python_executable: Optional[str] = None) -> bool:
        exe = python_executable or sys.executable
        try:
            completed = subprocess.run(
                [exe, "-c", "import mergekit.merge"],
                capture_output=True,
                text=True,
                timeout=120,
            )
        except (OSError, subprocess.SubprocessError):
            return False
        return completed.returncode == 0

    # ------------------------------------------------------------------ merge
    def merge(self, plan: MergePlan, candidate_id: str) -> MergedArtifact:
        plan.validate()
        if not plan.output_path:
            raise ValueError("MergekitBackend requires plan.output_path")

        os.makedirs(plan.output_path, exist_ok=True)
        yaml_path = os.path.join(plan.output_path, f"{candidate_id}_mergekit.yaml")
        with open(yaml_path, "w", encoding="utf-8") as handle:
            handle.write(build_mergekit_yaml(plan))

        command = [
            self.python_executable,
            "-m",
            "zeroai.merge.mergekit_driver",
            "--config",
            yaml_path,
            "--out",
            plan.output_path,
            "--device",
            self.device,
        ]
        if self.low_cpu_memory:
            command.append("--low-cpu-memory")
        if self.trust_remote_code:
            command.append("--trust-remote-code")
        if self.write_model_card:
            command.append("--write-model-card")
        if self.quiet:
            command.append("--quiet")

        LOG.debug("mergekit command: %s", " ".join(command))
        completed = subprocess.run(
            command,
            capture_output=True,
            text=True,
            timeout=self.timeout_seconds,
        )
        if completed.returncode != 0:
            raise RuntimeError(
                "mergekit driver failed "
                f"(exit {completed.returncode}) for {candidate_id!r}:\n"
                f"{completed.stderr.strip() or completed.stdout.strip()}"
            )

        stats = _parse_driver_stats(completed.stdout)
        return MergedArtifact(
            candidate_id=candidate_id,
            plan=plan,
            output_path=plan.output_path,
            deltas=None,
            stats=stats,
        )


def _parse_driver_stats(stdout: str) -> Dict[str, float]:
    for line in reversed(stdout.splitlines()):
        line = line.strip()
        if line.startswith("{\"zeroai_stats\""):
            try:
                payload = json.loads(line)
            except json.JSONDecodeError:
                continue
            return {k: float(v) for k, v in payload.items() if k != "zeroai_stats"}
    return {}